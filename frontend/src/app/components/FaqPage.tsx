const categories = Array.from(new Set(faqData.map((f) => f.category)));

export function FaqPage() {
  const [search, setSearch] = useState("");

  const filtered = useMemo(() => {
    if (!search.trim()) return faqData;
    const q = search.toLowerCase();
    return faqData.filter(
      (f) => f.q.toLowerCase().includes(q) || f.a.toLowerCase().includes(q) || f.category.toLowerCase().includes(q),
    );
  }, [search]);

  const grouped = useMemo(() => {
    const map = new Map<string, FaqItem[]>();
    for (const item of filtered) {
      if (!map.has(item.category)) map.set(item.category, []);
      map.get(item.category)!.push(item);
    }
    return map;
  }, [filtered]);

  return (
    <Card className="border border-gray-200 shadow-sm">
      <CardHeader className="border-b border-gray-200 bg-gray-50">
        <div className="flex items-center gap-3">
          <div className="flex items-center justify-center w-10 h-10 bg-blue-600 rounded-lg">
            <HelpCircle className="size-5 text-white" />
          </div>
          <div>
            <CardTitle className="text-xl font-semibold text-gray-900">
              Помощь и FAQ
            </CardTitle>
            <CardDescription className="text-sm text-gray-600">
              Ответы на частые вопросы о платформе
            </CardDescription>
          </div>
        </div>
      </CardHeader>
      <CardContent className="p-6 space-y-6">
        <div className="relative">
          <Search className="absolute left-3 top-1/2 -translate-y-1/2 size-4 text-gray-400" />
          <Input
            placeholder="Поиск по вопросам..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            className="pl-10 h-11 bg-white border-gray-300"
          />
        </div>

        <div className="space-y-6">
          {Array.from(grouped.entries()).map(([category, items]) => (
            <div key={category}>
              <div className="flex items-center gap-2 mb-3">
                <Badge variant="secondary" className="text-xs font-medium px-3 py-1">
                  {category}
                </Badge>
                <span className="text-xs text-gray-400">{items.length}</span>
              </div>
              <Accordion type="single" collapsible className="border border-gray-200 rounded-lg divide-y divide-gray-200">
                {items.map((item, idx) => (
                  <AccordionItem key={idx} value={`${category}-${idx}`} className="border-none">
                    <AccordionTrigger className="px-4 py-3 text-sm font-medium text-gray-900 hover:no-underline hover:bg-gray-50/50 transition-colors">
                      {item.q}
                    </AccordionTrigger>
                    <AccordionContent className="px-4 pb-4 text-sm text-gray-600 leading-relaxed">
                      {item.a}
                    </AccordionContent>
                  </AccordionItem>
                ))}
              </Accordion>
            </div>
          ))}

          {filtered.length === 0 && (
            <div className="text-center py-12 text-gray-400">
              <HelpCircle className="size-12 mx-auto mb-3 opacity-40" />
              <p className="text-sm">Ничего не найдено по запросу «{search}»</p>
            </div>
          )}
        </div>
      </CardContent>
    </Card>
  );
}
