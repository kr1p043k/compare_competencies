import math


# --------------------------------------------------------------
# 1. ИСХОДНАЯ ТАБЛИЦА ДАННЫХ
# --------------------------------------------------------------
data = [
    {"Возраст": 23, "Пол": "М", "Фирма": "Toyota"},
    {"Возраст": 45, "Пол": "Ж", "Фирма": "Honda"},
    {"Возраст": 67, "Пол": "М", "Фирма": "Ford"},
    {"Возраст": 34, "Пол": "М", "Фирма": "BMW"},
    {"Возраст": 52, "Пол": "Ж", "Фирма": "Toyota"},
    {"Возраст": 19, "Пол": "М", "Фирма": "Honda"},
    {"Возраст": 28, "Пол": "Ж", "Фирма": "Ford"},
    {"Возраст": 71, "Пол": "М", "Фирма": "BMW"},
    {"Возраст": 41, "Пол": "М", "Фирма": "Toyota"},
    {"Возраст": 36, "Пол": "Ж", "Фирма": "Honda"},
    {"Возраст": 58, "Пол": "М", "Фирма": "Ford"},
    {"Возраст": 25, "Пол": "М", "Фирма": "BMW"},
    {"Возраст": 63, "Пол": "Ж", "Фирма": "Toyota"},
    {"Возраст": 31, "Пол": "М", "Фирма": "Honda"},
    {"Возраст": 47, "Пол": "М", "Фирма": "Ford"},
    {"Возраст": 22, "Пол": "Ж", "Фирма": "BMW"},
    {"Возраст": 55, "Пол": "М", "Фирма": "Toyota"},
    {"Возраст": 39, "Пол": "Ж", "Фирма": "Honda"},
    {"Возраст": 68, "Пол": "М", "Фирма": "Ford"},
    {"Возраст": 29, "Пол": "М", "Фирма": "BMW"},
]

N = len(data)


# --------------------------------------------------------------
# 2. РАСЧЁТ ЧИСЛА ГРУПП И ДЛИНЫ ИНТЕРВАЛА ПО СТЕРДЖЕССУ
# --------------------------------------------------------------
# Число групп: n = 1 + 3.322 * lg(N)
n_raw = 1 + 3.322 * math.log10(N)      # ≈ 5.32
n = round(n_raw)                       # = 5

ages = [row["Возраст"] for row in data]
Xmin = min(ages)                       # = 19
Xmax = max(ages)                       # = 71

# Длина интервала: i = (Xmax - Xmin) / n
i_raw = (Xmax - Xmin) / n              # = 10.4
i_step = round(i_raw)                  # = 10 (два знака до запятой → до целых)

print("=" * 60)
print("ПРАВИЛО СТЕРДЖЕССА")
print("=" * 60)
print(f"N = {N}")
print(f"n = 1 + 3.322 * lg({N}) = {n_raw:.2f} ≈ {n}")
print(f"Xmin = {Xmin}, Xmax = {Xmax}")
print(f"i = ({Xmax} - {Xmin}) / {n} = {i_raw:.2f} ≈ {i_step}")


# --------------------------------------------------------------
# 3. ФОРМИРОВАНИЕ ГРАНИЦ И МЕТОК ГРУПП
# --------------------------------------------------------------
bounds = [Xmin + j * i_step for j in range(n)]     # [19, 29, 39, 49, 59]
bounds.append(10**9)                                # открытая последняя группа

labels = []
for j in range(n - 1):
    labels.append(f"{bounds[j]}–{bounds[j+1]-1}")
labels.append(f"{bounds[n-1]}+")

print()
print("Границы и метки групп:")
for lb, lo, hi in zip(labels, bounds[:-1], bounds[1:]):
    print(f"  {lb:<10} [{lo}; {hi})")


# --------------------------------------------------------------
# 4. КВАНТОВАНИЕ: ПОДСЧЁТ ЧИСЛА АВАРИЙ ПО ГРУППАМ
# --------------------------------------------------------------
counts = [0] * n

for j in range(N):
    age = data[j]["Возраст"]
    for g in range(n):
        if bounds[g] <= age < bounds[g + 1]:
            counts[g] += 1
            break


# --------------------------------------------------------------
# 5. ВЫВОД РЕЗУЛЬТАТА
# --------------------------------------------------------------
print()
print("=" * 60)
print("ИСХОДНАЯ ТАБЛИЦА (первые 5 записей)")
print("=" * 60)
print(f"{'№':<4} | {'Возраст':>8} | {'Пол':>4} | {'Фирма':<10}")
print("-" * 60)
for idx, row in enumerate(data[:5], 1):
    print(f"{idx:<4} | {row['Возраст']:>8} | {row['Пол']:>4} | {row['Фирма']:<10}")
print(f"... (всего {N} записей)")

print()
print("=" * 60)
print("РЕЗУЛЬТАТ КВАНТОВАНИЯ")
print("=" * 60)
print(f"{'Возрастная группа':<20} | {'Число аварий':>12}")
print("-" * 60)
for lb, cnt in zip(labels, counts):
    print(f"{lb:<20} | {cnt:>12}")
print("-" * 60)
print(f"{'ИТОГО':<20} | {sum(counts):>12}")
print(f"\nЗаписи не потеряны: {sum(counts) == N}")